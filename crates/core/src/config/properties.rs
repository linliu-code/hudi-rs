//! Java byte-stream properties and compatibility with the earlier native UTF-8 writer.

use crate::config::{Result, error::ConfigError::ParseLine};
use bytes::Bytes;
use std::collections::{HashMap, HashSet};

pub(crate) const NATIVE_PROPERTIES_CODEC: &str = "hoodie.read.native.properties.codec";
pub(crate) const JAVA_PROPERTIES_MARKER: &str = "# hudi-rs.properties.codec=java-v1";
const MARKER_PREFIX: &str = "# hudi-rs.properties.codec";
const NATIVE_HEADER: &str = "# Generated by hudi-rs";

pub(crate) fn validate_native_codec(codec: Option<&str>) -> Result<()> {
    match codec {
        None | Some("auto" | "legacy-utf8" | "java") => Ok(()),
        Some(value) => Err(ParseLine(format!(
            "invalid {NATIVE_PROPERTIES_CODEC}={value}; expected auto, legacy-utf8, or java"
        ))),
    }
}

pub(crate) fn parse_table_properties(
    bytes: &Bytes,
    codec: Option<&str>,
) -> Result<HashMap<String, String>> {
    validate_native_codec(codec)?;
    let mut marked = false;
    let mut native = false;
    for_each_logical_line(bytes, |line| {
        if let LogicalLine::Comment(line) = line {
            let comment = line.trim_end_matches([' ', '\t', '\u{c}']);
            native |= comment == NATIVE_HEADER;
            if comment.starts_with(MARKER_PREFIX) {
                if marked || comment != JAVA_PROPERTIES_MARKER {
                    return Err(ParseLine(
                        "unknown, malformed, or duplicate native properties codec marker"
                            .to_string(),
                    ));
                }
                marked = true;
            }
        }
        Ok(())
    })?;
    // Markers describe the individual file; a parent's fallback cannot override them.
    if marked || !native || codec == Some("java") {
        return parse_properties(bytes);
    }
    let legacy = crate::config::util::parse_data_for_options(bytes, "=");
    if codec == Some("legacy-utf8") {
        return legacy;
    }
    let java = parse_properties(bytes);
    if let (Ok(legacy), Ok(java)) = (&legacy, &java)
        && legacy == java
    {
        return Ok(java.clone());
    }
    // Both historical writers used the same header. Noncanonical escaped output can
    // exclude the newer writer, but canonical escapes alone cannot establish provenance.
    if !is_native_java_serialization(bytes) {
        return legacy;
    }
    Err(ParseLine(format!(
        "ambiguous unmarked native properties; set {NATIVE_PROPERTIES_CODEC}=legacy-utf8 \
         for the earlier raw UTF-8 writer or {NATIVE_PROPERTIES_CODEC}=java for escaped properties"
    )))
}

fn is_native_java_serialization(bytes: &[u8]) -> bool {
    if !bytes.is_ascii() {
        return false;
    }
    let mut keys = HashSet::new();
    for line in bytes.split(|byte| *byte == b'\n') {
        if line.is_empty() || line.starts_with(b"#") {
            continue;
        }
        let Ok(properties) = parse_properties(line) else {
            return false;
        };
        if properties.len() != 1 {
            return false;
        }
        for (key, value) in properties {
            let encoded = format!(
                "{}={}",
                escape_property(&key, true),
                escape_property(&value, false)
            );
            if encoded.as_bytes() != line || !keys.insert(key) {
                return false;
            }
        }
    }
    true
}

pub(crate) fn parse_properties(bytes: &[u8]) -> Result<HashMap<String, String>> {
    let mut properties = HashMap::new();
    for_each_logical_line(bytes, |line| {
        if let LogicalLine::Property(line) = line {
            parse_logical_line(line, &mut properties)?;
        }
        Ok(())
    })?;
    Ok(properties)
}

enum LogicalLine<'a> {
    Comment(&'a str),
    Property(&'a str),
}

fn for_each_logical_line(
    bytes: &[u8],
    mut consume: impl FnMut(LogicalLine<'_>) -> Result<()>,
) -> Result<()> {
    let mut logical = String::new();
    let mut offset = 0;
    while offset < bytes.len() {
        let end = bytes[offset..]
            .iter()
            .position(|byte| matches!(byte, b'\r' | b'\n'))
            .map_or(bytes.len(), |length| offset + length);
        // Java's byte-stream format is ISO-8859-1; Unicode uses UTF-16 escapes.
        let line: String = bytes[offset..end]
            .iter()
            .map(|byte| char::from(*byte))
            .collect();
        // Java checks EOF after the first terminator, before removing a continuation
        // slash. Thus a final "\\\n" emits an empty property, but "\\\r\n" does not.
        let at_eof = end == bytes.len() || end + 1 == bytes.len();
        offset = if bytes.get(end..end.saturating_add(2)) == Some(b"\r\n") {
            end + 2
        } else {
            (end + 1).min(bytes.len())
        };
        let line = line.trim_start_matches([' ', '\t', '\u{c}']);
        // An empty continuation does not make the next comment into property data.
        // Once any logical content exists, '#' and '!' are ordinary characters.
        if logical.is_empty() {
            if line.starts_with(['#', '!']) {
                consume(LogicalLine::Comment(line))?;
                continue;
            }
            if line.is_empty() {
                continue;
            }
        }
        logical.push_str(line);
        if has_continuation(&logical) {
            logical.pop();
            if !at_eof {
                continue;
            }
        }
        consume(LogicalLine::Property(&logical))?;
        logical.clear();
    }
    if !logical.is_empty() {
        consume(LogicalLine::Property(&logical))?;
    }
    Ok(())
}

fn has_continuation(line: &str) -> bool {
    line.bytes().rev().take_while(|byte| *byte == b'\\').count() % 2 == 1
}

fn parse_logical_line(line: &str, properties: &mut HashMap<String, String>) -> Result<()> {
    let mut escaped = false;
    let mut end = line.len();
    for (i, ch) in line.char_indices() {
        if !escaped && matches!(ch, '=' | ':' | ' ' | '\t' | '\u{c}') {
            end = i;
            break;
        }
        escaped = ch == '\\' && !escaped;
    }
    let mut value = line[end..].trim_start_matches([' ', '\t', '\u{c}']);
    if value.starts_with(['=', ':']) {
        value = &value[1..];
    }
    value = value.trim_start_matches([' ', '\t', '\u{c}']);
    properties.insert(unescape(&line[..end])?, unescape(value)?);
    Ok(())
}

fn unescape(input: &str) -> Result<String> {
    let mut units = Vec::with_capacity(input.len());
    let mut chars = input.chars();
    while let Some(ch) = chars.next() {
        let ch = if ch == '\\' {
            match chars.next() {
                Some('u') => {
                    let mut code = 0u16;
                    for _ in 0..4 {
                        let digit = chars.next().and_then(|c| c.to_digit(16)).ok_or_else(|| {
                            ParseLine("malformed Unicode escape in properties".to_string())
                        })?;
                        code = (code << 4) | digit as u16;
                    }
                    units.push(code);
                    continue;
                }
                Some('t') => '\t',
                Some('n') => '\n',
                Some('r') => '\r',
                Some('f') => '\u{c}',
                Some(ch) => ch,
                None => break,
            }
        } else {
            ch
        };
        let mut encoded = [0; 2];
        units.extend_from_slice(ch.encode_utf16(&mut encoded));
    }
    String::from_utf16(&units).map_err(|e| ParseLine(format!("invalid UTF-16 in properties: {e}")))
}

pub(crate) fn escape_property(input: &str, key: bool) -> String {
    let mut out = String::new();
    for (i, ch) in input.chars().enumerate() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '\t' => out.push_str("\\t"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\u{c}' => out.push_str("\\f"),
            ' ' if key || i == 0 => out.push_str("\\ "),
            '=' | ':' | '#' | '!' => {
                out.push('\\');
                out.push(ch);
            }
            ch if !(' '..='~').contains(&ch) => {
                let mut units = [0; 2];
                for unit in ch.encode_utf16(&mut units) {
                    out.push_str(&format!("\\u{unit:04X}"));
                }
            }
            ch => out.push(ch),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_java_empty_continuations_do_not_continue_comments() {
        for newline in ["\n", "\r\n", "\r"] {
            for comment in ["# ignored\\", "! ignored\\"] {
                let input = format!(
                    "key=old{newline}\\{newline} \t\u{c}{comment}{newline}key=new{newline}"
                );
                assert_eq!(
                    parse_properties(input.as_bytes()).unwrap(),
                    HashMap::from([("key".to_string(), "new".to_string())])
                );
                let input = format!("key=kept\\{newline}{comment}{newline}next=value{newline}");
                assert_eq!(
                    parse_properties(input.as_bytes()).unwrap(),
                    HashMap::from([(
                        "key".to_string(),
                        format!("kept{comment}next=value").replace("\\", "")
                    )])
                );
            }
        }
    }

    #[test]
    fn test_java_empty_continuation_eof_matches_input_stream() {
        // Verified with java.util.Properties.load(InputStream), including its
        // lookahead before CRLF consumption at EOF.
        for (input, empty_key) in [
            (b"\\".as_slice(), true),
            (b"\\\n", true),
            (b"\\\r", true),
            (b"\\\r\n", false),
            (b"\\\n ", false),
            (b"\\\n\t", false),
            (b"\\\n\n", false),
            (b"\\\n \\", true),
            (b"\\\n# ignored\\", false),
            (b"\\\n! ignored\\\n", false),
        ] {
            let expected = if empty_key {
                HashMap::from([(String::new(), String::new())])
            } else {
                HashMap::new()
            };
            assert_eq!(parse_properties(input).unwrap(), expected, "{input:?}");
        }
    }

    #[test]
    fn test_empty_continuations_preserve_native_marker_authority() {
        for newline in ["\n", "\r\n", "\r"] {
            let prefix = format!("\\{newline} \t\u{c}");
            for marker in [
                "# hudi-rs.properties.codec=unknown".to_string(),
                format!("{JAVA_PROPERTIES_MARKER}{newline}{JAVA_PROPERTIES_MARKER}"),
            ] {
                let bytes = Bytes::from(format!("{prefix}{marker}{newline}key=value"));
                assert!(parse_table_properties(&bytes, None).is_err());
            }
            let bytes = Bytes::from(format!(
                "{NATIVE_HEADER}{newline}{prefix}{JAVA_PROPERTIES_MARKER}{newline}key=line\\nnext"
            ));
            assert_eq!(
                parse_table_properties(&bytes, Some("legacy-utf8")).unwrap()["key"],
                "line\nnext"
            );
        }
        // The historical UTF-8 writer used LF; its separate decoder stays unchanged.
        let bytes = Bytes::from(format!("\\\n{NATIVE_HEADER}\nkey=café"));
        assert_eq!(parse_table_properties(&bytes, None).unwrap()["key"], "café");
    }

    #[test]
    fn test_java_continued_values_are_not_native_provenance_comments() {
        for suffix in [
            "# Generated by hudi-rs",
            "# hudi-rs.properties.codec=java-v99",
            "# hudi-rs.properties.codec=java-v1",
        ] {
            for newline in ["\n", "\r\n", "\r"] {
                for indent in ["", " \t\u{c}"] {
                    let bytes =
                        Bytes::from(format!("key=continued\\{newline}{indent}{suffix}{newline}"));
                    assert_eq!(
                        parse_table_properties(&bytes, None).unwrap(),
                        parse_properties(&bytes).unwrap()
                    );
                }
            }
        }
        for prefix in ["# comment\\", "! comment\\", r"key=even\\", r"key=space\ "] {
            let bytes = Bytes::from(format!(
                "{prefix}\n# hudi-rs.properties.codec=unknown\nkey=value\n"
            ));
            assert!(parse_table_properties(&bytes, None).is_err(), "{prefix}");
        }
    }

    #[test]
    fn test_native_detection_checks_every_property_without_guessing() {
        for (raw, legacy, java) in [
            (r"line\nnext", r"line\nnext", "line\nnext"),
            (r"path\\next", r"path\\next", r"path\next"),
            (r"caf\u00E9", r"caf\u00E9", "café"),
            (r"\ leading", r"\ leading", " leading"),
        ] {
            let bytes = Bytes::from(format!(
                "# Generated by hudi-rs\nhoodie.table.name=same\nsafe=value\nother={raw}\n"
            ));
            assert!(is_native_java_serialization(&bytes));
            assert!(parse_table_properties(&bytes, None).is_err());
            assert_eq!(
                parse_table_properties(&bytes, Some("legacy-utf8")).unwrap()["other"],
                legacy
            );
            assert_eq!(
                parse_table_properties(&bytes, Some("java")).unwrap()["other"],
                java
            );
        }
        let bytes = Bytes::from_static(b"# Generated by hudi-rs\nsafe=value\nkey\\:name=value\n");
        assert!(parse_table_properties(&bytes, None).is_err());
        assert_eq!(
            parse_table_properties(&bytes, Some("legacy-utf8")).unwrap()[r"key\:name"],
            "value"
        );
        assert_eq!(
            parse_table_properties(&bytes, Some("java")).unwrap()["key:name"],
            "value"
        );
        let same = Bytes::from_static(b"# Generated by hudi-rs\nsafe=value\nempty=\n");
        assert_eq!(
            parse_table_properties(&same, None).unwrap(),
            parse_properties(&same).unwrap()
        );
    }

    #[test]
    fn test_native_exclusion_and_decoder_failures_are_distinct() {
        for suffix in [
            "key=café\n",
            "key=raw:colon\n",
            "key=C:\\user\n",
            "key=\\uNOT0\n",
            "key=\\uD800\n",
            "key=first\nkey=second\n",
        ] {
            let bytes = Bytes::from(format!("# Generated by hudi-rs\n{suffix}"));
            assert!(!is_native_java_serialization(&bytes), "{suffix}");
            assert_eq!(
                parse_table_properties(&bytes, None).unwrap(),
                crate::config::util::parse_data_for_options(&bytes, "=").unwrap()
            );
        }
        let invalid_utf8 = Bytes::from_static(b"# Generated by hudi-rs\nkey=\xff\n");
        assert!(parse_table_properties(&invalid_utf8, None).is_err());
        let marked = Bytes::from(format!("{JAVA_PROPERTIES_MARKER}\nkey=\\uNOT0\n"));
        assert!(parse_table_properties(&marked, Some("legacy-utf8")).is_err());
        let java = Bytes::from_static(b"# Java properties\nkey=\xe9\n");
        assert_eq!(
            parse_table_properties(&java, Some("legacy-utf8")).unwrap()["key"],
            "é"
        );
    }

    #[test]
    fn test_java_properties_grammar_and_unicode() {
        // Equivalent to java.util.Properties.load on this byte stream.
        let bytes = b"!comment\r\n  key\\ with\\ spaces : \\ leading\\tvalue  \r\ncontinued=one\\\r\n  two\nlatin=\xe9\nunicode=\\uD83D\\uDE00\nempty\n";
        let props = parse_properties(bytes).unwrap();
        assert_eq!(props["key with spaces"], " leading\tvalue  ");
        assert_eq!(props["continued"], "onetwo");
        assert_eq!(props["latin"], "é");
        assert_eq!(props["unicode"], "😀");
        assert_eq!(props["empty"], "");
        assert!(parse_properties(br"bad=\uNOT0").is_err());
        assert!(parse_properties(br"bad=\uD800").is_err());
    }

    #[test]
    fn test_properties_roundtrip_special_values() {
        for value in [
            "café",
            "😀",
            " leading and trailing ",
            "line\nnext\t",
            r"path\next",
            "=:#!",
        ] {
            let key = " key:=\\";
            let encoded = format!(
                "{}={}\n",
                escape_property(key, true),
                escape_property(value, false)
            );
            assert!(encoded.is_ascii());
            assert_eq!(parse_properties(encoded.as_bytes()).unwrap()[key], value);
        }
    }
}
